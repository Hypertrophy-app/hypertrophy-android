import java.util.Properties

plugins {
    alias(libs.plugins.android.library)
    alias(libs.plugins.kotlin.serialization)
    alias(libs.plugins.ksp)
    alias(libs.plugins.hilt)
}

android {
    namespace = "app.hypertrophy.core.data"
    compileSdk = libs.versions.compileSdk.get().toInt()

    defaultConfig {
        minSdk = libs.versions.minSdk.get().toInt()
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

        // The Worker host differs per environment. local.properties (gitignored)
        // or -PHYPERTROPHY_API_BASE_URL can point at a branded domain; the
        // deployed workers.dev host is the default so debug builds just work.
        val localProperties = Properties()
        val localPropertiesFile = rootProject.file("local.properties")
        if (localPropertiesFile.exists()) {
            localPropertiesFile.inputStream().use { localProperties.load(it) }
        }
        val apiBaseUrl = localProperties.getProperty("HYPERTROPHY_API_BASE_URL")
            ?: providers.gradleProperty("HYPERTROPHY_API_BASE_URL").orNull
            ?: "https://hypertrophy-api.watchllm.workers.dev"
        buildConfigField("String", "API_BASE_URL", "\"$apiBaseUrl\"")
    }

    buildFeatures {
        buildConfig = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
}

